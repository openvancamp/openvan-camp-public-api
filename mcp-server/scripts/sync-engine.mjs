#!/usr/bin/env node
/**
 * Копия движка роудбука для npm-пакета.
 *
 * Развёрнутый сервер берёт движок прямо из репозитория сайта (resources/js/roadbook) —
 * правки роудбука доходят до plan_road_trip сами. В npm-пакете сайта нет, поэтому перед
 * публикацией сюда, в engine/, копируются ровно те файлы, что импортирует plan.js.
 * Структура папок та же, что в resources/js: относительные импорты движка не меняются.
 *
 * Часть файлов сайта — переходники на общий с ParkX модуль: `export * from
 * "@map-features/route/…"` (в vite.config.js это alias). Их цели копируются в
 * engine/map-features/, там их ищет src/engine/plan-worker.ts. Цель, которой нет,
 * — ошибка: пакет без неё падал бы на каждом plan_road_trip.
 *
 *   node scripts/sync-engine.mjs [путь к resources/js] [путь к map-features]
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const from = resolve(process.argv[2] ?? join(here, "../../resources/js"));
const to = resolve(here, "../engine");
const mapFeatures = resolve(process.argv[3] ?? join(from, "../../../map-features"));

const FILES = ["roadbook/plan.js", "roadbook/plan", "roadbook/rows", "visa-calc-core.js", "fuel-calc-core.js", "geo/country-at.js"];

if (!existsSync(join(from, "roadbook/plan.js"))) {
  console.error(`Roadbook engine not found in ${from}`);
  process.exit(1);
}

rmSync(to, { recursive: true, force: true });
for (const f of FILES) {
  mkdirSync(dirname(join(to, f)), { recursive: true });
  cpSync(join(from, f), join(to, f), { recursive: true });
}
// Файлы общего модуля, на которые ссылается движок, и их соседи по относительным импортам.
const walk = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));
const queue = walk(to).filter((f) => f.endsWith(".js"))
  .flatMap((f) => [...readFileSync(f, "utf8").matchAll(/["']@map-features\/([^"']+)["']/g)].map((m) => m[1]));
const seen = new Set();
while (queue.length) {
  const rel = queue.shift();
  if (seen.has(rel)) continue;
  seen.add(rel);
  const src = join(mapFeatures, rel);
  if (!existsSync(src)) {
    console.error(`@map-features/${rel} not found in ${mapFeatures}`);
    process.exit(1);
  }
  mkdirSync(dirname(join(to, "map-features", rel)), { recursive: true });
  cpSync(src, join(to, "map-features", rel));
  if (!rel.endsWith(".js")) continue;
  for (const m of readFileSync(src, "utf8").matchAll(/(?:from\s*|import\(\s*)["'](\.{1,2}\/[^"']+)["']/g)) {
    queue.push(join(dirname(rel), m[1]));
  }
}
if (seen.size) console.log(`map-features: ${[...seen].join(", ")}`);
writeFileSync(join(to, "package.json"), JSON.stringify({ type: "module" }, null, 2) + "\n");
writeFileSync(join(to, "README.md"), "Copy of the OpenVan roadbook plan engine (resources/js of openvan.camp), generated by scripts/sync-engine.mjs. Do not edit here.\n");
console.log(`Engine copied: ${from} → ${to}`);
